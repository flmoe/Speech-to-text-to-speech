import vosk
from multiprocessing import Process, Pipe


def remove_junk(str):
    '''extract raw text from recogniser output'''
    str = str.replace('"', '')
    str = str.split('\n')[1]
    return str.split(':')[1].strip()


def _run(conn, model_path):
    # disable stt log output
    vosk.SetLogLevel(-1)
    # load language model
    model = vosk.Model(model_path)
    recog = None
    invalid_cnt = 0
    # main loop
    while True:
        data = conn.recv()
        # termination signal
        if data is None:
            return
        # initialise recogniser
        elif data[0] == 'rate':
            recog = vosk.KaldiRecognizer(model, data[1])
        elif data[0] == 'audio':
            # recogniser not initialised
            if recog is None:
                continue
            # ignore output generated by "silent" blocks
            # fixes the "random hey" bug
            if data[2]:
                invalid_cnt = 0
            else:
                invalid_cnt += 1
            # speech to text
            # only start returning words after some time
            # because early output might change
            if recog.AcceptWaveform(data[1]) and invalid_cnt < 25:
                result = recog.Result()
                result = remove_junk(result)
                if result:
                    conn.send(result)


class STT():

    def __init__(self, model_path):
        self.conn, run_conn = Pipe()
        self.proc = Process(target=_run, args=(run_conn, model_path))

    def pass_audio(self, data, valid):
        self.conn.send(('audio', data, valid))

    def get_text(self):
        text = ''
        while self.conn.poll():
            text = text + ' ' + self.conn.recv()
        return text.strip()

    def set_rate(self, samplerate):
        self.conn.send(('rate', samplerate))

    def terminate(self):
        self.conn.send(None)


